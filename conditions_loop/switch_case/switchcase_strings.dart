void main() {
  const cuaca = "cerah";

  switch (cuaca) {
    case "cerah":
      print("Cuaca hari ini cerah");
      break;
    case "hujan":
      print("Cuaca hari ini hujan");
      break;
    case "mendung":
      print("Cuaca hari ini mendung");
      break;
    default:
      print("Cuaca tidak diketahui");
  }
}
